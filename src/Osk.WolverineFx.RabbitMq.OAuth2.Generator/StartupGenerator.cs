using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Text;

namespace Osk.WolverineFx.RabbitMq.OAuth2.Generator;

/// <summary>Добавляет в сборку потребителя автоматическую установку Harmony-патчей Wolverine.</summary>
/// <remarks>Генерирует метод с атрибутом ModuleInitializer. Среда выполнения вызывает его при инициализации модуля, до первого обращения к его типам или методам, в том числе до Main в исполняемой сборке. Явная регистрация патчей потребителем не требуется.</remarks>
[Generator]
public sealed class StartupGenerator : IIncrementalGenerator
{
    private static readonly SourceText SourceText = SourceText.From(
        """
        // <auto-generated/>
        namespace Osk.WolverineFx.RabbitMq.OAuth2.Generated
        {
            /// <summary>Обеспечивает автоматическую установку патчей при инициализации модуля потребителя.</summary>
            internal static class RabbitMqOAuth2Startup
            {
                /// <summary>Устанавливает Harmony-патчи до первого обращения к типам или методам модуля, включая Main.</summary>
                /// <remarks>Вызывается средой выполнения при инициализации модуля. Повторная установка в процессе безопасна.</remarks>
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Initialize()
                {
                    global::Osk.WolverineFx.RabbitMq.OAuth2.RabbitMqOAuth2Patches.Install();
                }
            }
        }
        """, Encoding.UTF8);

    /// <summary>Регистрирует добавление исходного кода инициализатора независимо от синтаксиса проекта потребителя.</summary>
    /// <param name="context">Контекст регистрации шагов инкрементального генератора Roslyn.</param>
    /// <remarks>Исходный код добавляется на этапе постинициализации генератора при компиляции; сами патчи устанавливаются при выполнении сгенерированного инициализатора модуля.</remarks>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => output.AddSource(
            "RabbitMqOAuth2Startup.g.cs", SourceText));
    }
}